a = int(input("Введите возраст: "))
if a < 0 or a > 120:
    print("Ошибка")
elif a <= 6:
    print("Стоимость билета: 0 руб.")
elif a <= 12:
    print("Стоимость билета: 300 руб.")
elif a <= 17:
    print("Стоимость билета: 500 руб.")
elif a <= 65:
    print("Стоимость билета: 800 руб.")
else:
    print("Стоимость билета: 400 руб.")